#!/usr/bin/env node
// Encoding facts come only from x86_table. Semantic coverage is deliberately separate.
import fs from "node:fs";
import assert from "node:assert/strict";
import table from "./x86_table.js";
import {experimentalLowering, experimentalTests} from "./ir_semantics.js";
const hex = n => n.toString(16).toUpperCase();
const familyKey = opcode => (opcode & 0xFF00) === 0x0F00 ? opcode & 0xFFFF : opcode & 0xFF;
const familyModrm = new Map();
for(const e of table) if(!familyModrm.has(familyKey(e.opcode))) familyModrm.set(familyKey(e.opcode), !!e.e);
const rows = table.filter(e => !e.prefix).map(e => ({...e,
    id: e.opcode * 16 + (e.fixed_g === undefined ? 0 : e.fixed_g + 1),
    fetch_modrm: familyModrm.get(familyKey(e.opcode)),
})).sort((a, b) => a.id - b.id);
assert.equal(new Set(rows.map(e => e.id)).size, rows.length);
const bool = x => x ? "true" : "false";
const imm = e => e.imm8 ? "Byte" : e.imm8s ? "SignedByte" : e.imm16 ? "Word" :
    e.imm1632 ? "Operand" : e.immaddr ? "Address" : "None";
const flags = ["fetch_modrm", "custom", "e", "ignore_mod", "reg_ud", "mem_ud", "os", "block_boundary", "no_next_instruction",
    "absolute_jump", "jump_offset_imm", "conditional_jump", "custom_sti", "is_fpu", "sse", "is_string"];
let rust = "// Generated by gen/generate_ir_decoder.js. Do not edit.\nuse super::{Encoding, ImmediateKind};\npub static ENCODINGS: &[Encoding] = &[\n";
for(const e of rows) {
    rust += `    Encoding { id: ${e.id}, opcode: 0x${hex(e.opcode)}, group: ${e.fixed_g ?? -1}, immediate: ImmediateKind::${imm(e)}, extra_bytes: ${e.extra_imm16 ? 2 : e.extra_imm8 ? 1 : 0}, ${flags.map(k => `${k}: ${bool(e[k])}`).join(", ")} },\n`;
}
rust += "];\n";
// Bounded binary search over a generated opcode-key index, followed by <= 8 group entries.
const buckets = new Map();
for(let i = 0; i < rows.length; i++) {
    const opcode = rows[i].opcode;
    if(!buckets.has(opcode)) buckets.set(opcode, [i, i]);
    buckets.get(opcode)[1] = i + 1;
}
rust += "pub static OPCODES: &[(u32, usize, usize)] = &[\n";
for(const [opcode, [start, end]] of buckets) rust += `    (0x${hex(opcode)}, ${start}, ${end}),\n`;
rust += "];\n";
const forms = [];
for(const e of rows) for(const operand_size of e.os ? [16, 32] : [null])
    for(const address_size of [16, 32]) for(const operand of e.e && !e.ignore_mod ? ["reg", "mem"] : [e.e ? "reg" : "implicit"]) {
        const invalid = operand === "reg" && e.reg_ud || operand === "mem" && e.mem_ud;
        forms.push({encoding_id: e.id, key: `${hex(e.opcode)}/${e.fixed_g ?? "-"}/${operand_size ?? "fixed"}/${address_size}/${operand}`,
            operand_size, address_size, operand,
            lowering: invalid ? "BaselineUD" : "Pending",
            experimental_lowering: invalid ? "BaselineUD" : experimentalLowering(e, operand),
            tests: invalid ? ["tests/ir/decode/decode.rs"] : experimentalTests(e, operand)});
    }
const coverage = {schema: 1, source: "gen/x86_table.js", encodings: rows.length, forms,
    note: "Encoding forms are not a claim of semantic coverage. Pending includes unimplemented native and helper lowering. Prefix repetitions, mode guards and nested x87 subforms require additional tests."};
const coverageText = JSON.stringify({...coverage, forms: undefined}, null, 2).slice(0, -2) +
    ',\n  "forms": [\n' + forms.map(f => "    " + JSON.stringify(f)).join(",\n") + "\n  ]\n}\n";
const outputs = [["src/rust/ir/frontend/encodings.rs", rust], ["docs/ir-coverage.json", coverageText]];
for(const [path, content] of outputs) {
    if(process.argv.includes("--check")) assert.equal(fs.readFileSync(path, "utf8"), content, `${path} is stale`);
    else fs.writeFileSync(path, content);
}
console.log(`IR catalogue: ${rows.length} encodings, ${forms.length} forms, ${forms.filter(f => f.lowering === "Pending").length} pending`);
